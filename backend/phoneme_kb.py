def get_phoneme(symbol: str) -> dict[str, Any] | None:
    """Return the full knowledge-base entry for an IPA symbol (exact match only)."""
    return PHONEMES.get(symbol)


def substitution_tip(expected: str, actual: str) -> str | None:
    """Return coaching for saying ``actual`` where ``expected`` was required."""
    return SUBSTITUTION_TIPS.get((expected, actual))


def deletion_tip(expected: str) -> str | None:
    """Return coaching for dropping the ``expected`` phoneme entirely."""
    return DELETION_TIPS.get(expected)


def list_phonemes() -> list[dict[str, Any]]:
    """Return summary entries for every phoneme in chart order."""
    return [
        {**{field: entry[field] for field in _SUMMARY_FIELDS}, "examples": list(entry["examples"])}
        for entry in PHONEMES.values()
    ]
